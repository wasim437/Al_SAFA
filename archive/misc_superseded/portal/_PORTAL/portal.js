let SEARCH_INDEX = [];

function renderPalette(query) {
    const q = query.trim().toLowerCase();
    const pool = q
        ? SEARCH_INDEX
            .map(it => {
                const t = it.title.toLowerCase(), s = (it.sub || '').toLowerCase();
                let score = -1;
                if (t.startsWith(q)) score = 0;
                else if (t.includes(q)) score = 1;
                else if (s.includes(q)) score = 2;
                return { it, score };
            })
            .filter(r => r.score >= 0)
            .sort((a, b) => a.score - b.score)
            .map(r => r.it)
            .slice(0, 40)
        : SEARCH_INDEX.filter(it => it.kind === 'page');

    paletteItems = pool;
    paletteIndex = 0;

    const box = $('#paletteResults');
    if (!pool.length) {
        box.innerHTML = `<div class="palette-empty">Nothing matches “${esc(query)}”.</div>`;
        return;
    }

    let html = '', lastKind = null;
    pool.forEach((it, i) => {
        if (it.kind !== lastKind) {
            const labels = { page: 'Pages', metric: 'Metrics', zone: 'Zones',
                             species: 'Species', problem: 'Problems', source: 'Source files',
                             reference: 'References' };
            html += `<div class="palette-group">${labels[it.kind] || it.kind}</div>`;
            lastKind = it.kind;
        }
        html += `<button class="palette-item${i === 0 ? ' sel' : ''}" data-i="${i}" role="option">
            <span class="palette-ico">${it.ico}</span>
            <span class="palette-label"><b>${esc(it.title)}</b><small>${esc(it.sub || '')}</small></span>
            <span class="palette-kind">${it.kind}</span>
        </button>`;
    });
    box.innerHTML = html;
}

function paletteMove(delta) {
    const items = $$('.palette-item');
    if (!items.length) return;
    paletteIndex = (paletteIndex + delta + items.length) % items.length;
    items.forEach((el, i) => el.classList.toggle('sel', i === paletteIndex));
    items[paletteIndex].scrollIntoView({ block: 'nearest' });
}

function paletteChoose(i) {
    const it = paletteItems[i];
    if (!it) return;
    closePalette();
    showPage(it.page);
    if (it.prov) setTimeout(() => openDrawer(it.prov), 220);
}

