/* ==========================================================================
   12. Site layout — shared by the 2D plan and the 3D model
   --------------------------------------------------------------------------
   Block sizes are derived from the real zoning areas, so the drawings are a
   true representation of the schedule rather than a decorative diagram.
   Site envelope is the project's assumed 150 x 100 m rectangle (still to be
   confirmed against the municipality DWG).
   ========================================================================== */
const SITE_W = 150, SITE_H = 100;

function computeLayout() {
    const byName = {};
    D.zoning.zones.forEach(z => { byName[z.fullName] = z; });

    const blocks = [];
    const put = (name, x, y, w, h) => {
        const z = byName[name];
        if (!z) return;
        blocks.push({ zone: z, x, y, w, h });
    };

    // Perimeter buffers: full-width strips, depth derived from their real area.
    const bufN = byName['Perimeter Shade Buffer (N)'];
    const bufS = byName['Perimeter Shade Buffer (S)'];
    const dN = bufN ? bufN.area / SITE_W : 0;
    const dS = bufS ? bufS.area / SITE_W : 0;
    put('Perimeter Shade Buffer (S)', 0, 0, SITE_W, dS);
    put('Perimeter Shade Buffer (N)', 0, SITE_H - dN, SITE_W, dN);

    // Entrance plazas bookend the spine; spine fills the gap between them.
    const ent = byName['Main Entrance Plaza'];
    const entW = 12, entH = ent ? ent.area / entW : 20;   // 240 / 12 = 20 m deep
    const spine = byName['Shaded Spine (Central Walkway)'];
    const spineLen = SITE_W - 2 * entW;                    // 126 m
    const spineW = spine ? spine.area / spineLen : 10;     // 1260 / 126 = 10 m
    const midY = SITE_H / 2;

    put('Main Entrance Plaza', 0, midY - entH / 2, entW, entH);
    put('Secondary Entrance (E)', SITE_W - entW, midY - entH / 2, entW, entH);
    put('Shaded Spine (Central Walkway)', entW, midY - spineW / 2, spineLen, spineW);

    // Two activity bands either side of the spine. Depth is fixed; each block's
    // width = area / depth, so relative areas stay exact. Whatever is left over
    // reads as the circulation and setback network.
    const BAND_DEPTH = 30;
    const layBand = (names, yBase) => {
        const widths = names.map(n => (byName[n] ? byName[n].area / BAND_DEPTH : 0));
        const used = widths.reduce((a, b) => a + b, 0);
        const gap = (SITE_W - used) / (names.length + 1);
        let x = gap;
        names.forEach((n, i) => {
            put(n, x, yBase, widths[i], BAND_DEPTH);
            x += widths[i] + gap;
        });
    };

    // 6 m of clearance keeps the bands clear of the entrance plazas, which are
    // 20 m deep and straddle the spine axis at either end.
    const CLEARANCE = 6;
    const northBase = midY + spineW / 2 + CLEARANCE;
    const southBase = midY - spineW / 2 - CLEARANCE - BAND_DEPTH;

    layBand(["Children's Play Zone", 'Family Picnic & Shaded Seating',
             'Community Plaza & Event Lawn', 'Outdoor Fitness & Wellness'], northBase);
    layBand(['Native Planting / Biodiversity Strip', 'Quiet Contemplation Garden',
             'Commercial & Service Kiosk Cluster', 'Multipurpose Sports Lawn'], southBase);

    return blocks;
}

