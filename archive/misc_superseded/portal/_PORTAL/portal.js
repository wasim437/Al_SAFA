function tableToCsv(tableId) {
    const table = document.getElementById(tableId);
    if (!table) return '';
    return $$('tr', table).map(tr =>
        $$('th,td', tr).map(cell => {
            const text = cell.innerText.replace(/\s+/g, ' ').trim();
            return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
        }).join(',')
    ).join('\r\n');
}

