function showPage(id, pushHash) {
    if (!PAGES.includes(id)) id = 'overview';

    $$('.page').forEach(p => p.classList.remove('active'));
    const page = document.getElementById('page-' + id);
    if (page) page.classList.add('active');

    $$('.nav-link').forEach(l => {
        const on = l.dataset.page === id;
        l.classList.toggle('active', on);
        l.setAttribute('aria-current', on ? 'page' : 'false');
    });

    if (pushHash !== false) location.hash = id;

    // Charts and canvases size to zero while hidden, so build on first reveal.
    if (!pageInited[id] && pageInit[id]) { pageInit[id](); pageInited[id] = true; }

    closeNav();
    window.scrollTo({ top: 0, behavior: 'instant' in document.documentElement.style ? 'instant' : 'auto' });

    // Move focus to the new heading so screen readers and keyboard users land in
    // the right place — but not on first paint, where an unprompted focus ring
    // on the title just looks like a rendering fault.
    if (page && !firstPaint) {
        const h = page.querySelector('.page-title');
        if (h) { h.setAttribute('tabindex', '-1'); h.focus({ preventScroll: true }); }
    }
    firstPaint = false;
}

