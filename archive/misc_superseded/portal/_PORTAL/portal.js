let weights = null;

function conceptTotals() {
    const total = weights.reduce((a, b) => a + b, 0) || 1;
    return D.concepts.options.map(o => ({
        id: o.id, name: o.name, selected: o.selected,
        total: o.scores.reduce((sum, s, i) => sum + s * weights[i], 0) / total,
    }));
}

function renderConceptResults() {
    const totals = conceptTotals();
    const best = totals.reduce((a, b) => (b.total > a.total ? b : a));
    const chosen = totals.find(t => t.selected);

    $('#winnerLabel').innerHTML = `leader: <strong style="color:var(--gold)">
        Concept ${best.id}</strong> at ${best.total.toFixed(2)}`;

    const note = $('#robustnessNote').querySelector('div');
    if (best.id === chosen.id) {
        const runnerUp = totals.filter(t => t.id !== best.id)
                               .reduce((a, b) => (b.total > a.total ? b : a));
        const margin = (best.total - runnerUp.total).toFixed(2);
        $('#robustnessNote').className = 'callout good';
        note.innerHTML = `Concept A still wins under these weights, by
            <strong>${margin} points</strong> over Concept ${runnerUp.id}. The selection is
            not an artefact of the weighting — try pushing Sustainability or Innovation up
            and watch how far you have to go before the ranking flips.`;
    } else {
        $('#robustnessNote').className = 'callout warn';
        note.innerHTML = `Under these weights <strong>Concept ${best.id}
            (${esc(best.name)})</strong> would win instead, at ${best.total.toFixed(2)} against
            Concept A's ${chosen.total.toFixed(2)}. That is a legitimate finding: it shows
            exactly which priorities would justify a different scheme.`;
    }

    if (charts.conceptChart) {
        charts.conceptChart.data.datasets[0].data = totals.map(t => Number(t.total.toFixed(2)));
        charts.conceptChart.data.datasets[0].backgroundColor = totals.map(t => {
            const c = PALETTE();
            return t.id === best.id ? alpha(c.gold, 0.85) : alpha(c.muted, 0.4);
        });
        charts.conceptChart.update();
    }

    $$('#conceptCards .concept').forEach(card => {
        card.classList.toggle('win', card.dataset.concept === best.id);
        $('.concept-score', card).textContent =
            totals.find(t => t.id === card.dataset.concept).total.toFixed(2);
    });
}

