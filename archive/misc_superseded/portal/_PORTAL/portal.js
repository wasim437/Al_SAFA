let zoningHover = -1;

function drawZoningPlan() {
    const canvas = $('#zoningCanvas');
    if (!canvas) return;
    const dpr = window.devicePixelRatio || 1;
    const W = canvas.clientWidth, H = canvas.clientHeight;
    if (!W || !H) return;
    canvas.width = W * dpr; canvas.height = H * dpr;
    const ctx = canvas.getContext('2d');
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, W, H);

    const pad = 26;
    const scale = Math.min((W - pad * 2) / SITE_W, (H - pad * 2) / SITE_H);
    const ox = (W - SITE_W * scale) / 2;
    const oy = (H - SITE_H * scale) / 2;
    // Canvas y grows downward; the site model has y growing north.
    const px = (x) => ox + x * scale;
    const py = (y) => oy + (SITE_H - y) * scale;

    // Site outline
    ctx.fillStyle = cssVar('--bg-inset');
    ctx.fillRect(px(0), py(SITE_H), SITE_W * scale, SITE_H * scale);
    ctx.strokeStyle = cssVar('--line');
    ctx.lineWidth = 1.5;
    ctx.strokeRect(px(0), py(SITE_H), SITE_W * scale, SITE_H * scale);

    const colors = TOKEN_COLOR();

    LAYOUT.forEach((b, i) => {
        const color = colors[b.zone.token] || colors.blue;
        const hovered = i === zoningHover;
        ctx.fillStyle = alpha(color, hovered ? 0.55 : 0.28);
        ctx.strokeStyle = alpha(color, hovered ? 1 : 0.7);
        ctx.lineWidth = hovered ? 2 : 1;
        const x = px(b.x), y = py(b.y + b.h);
        const w = b.w * scale, h = b.h * scale;
        ctx.beginPath();
        if (ctx.roundRect) ctx.roundRect(x, y, w, h, 3); else ctx.rect(x, y, w, h);
        ctx.fill(); ctx.stroke();

        // Icon, only where the block is big enough to carry it.
        if (w > 26 && h > 22) {
            ctx.font = `${Math.min(15, w / 3, h / 2)}px system-ui`;
            ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
            ctx.fillStyle = 'rgba(255,255,255,0.85)';
            ctx.fillText(b.zone.icon, x + w / 2, y + h / 2);
        }
    });

    // North arrow + scale bar
    ctx.textAlign = 'center'; ctx.textBaseline = 'alphabetic';
    ctx.fillStyle = cssVar('--text-muted');
    ctx.font = '600 11px system-ui, sans-serif';
    ctx.fillText('N ▲', px(SITE_W) - 16, py(SITE_H) - 8);

    const barM = 25, bx = px(0), by = py(0) + 15;
    ctx.strokeStyle = cssVar('--text-muted'); ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(bx, by); ctx.lineTo(bx + barM * scale, by);
    ctx.moveTo(bx, by - 3); ctx.lineTo(bx, by + 3);
    ctx.moveTo(bx + barM * scale, by - 3); ctx.lineTo(bx + barM * scale, by + 3);
    ctx.stroke();
    ctx.textAlign = 'left';
    ctx.fillText(`${barM} m`, bx + barM * scale + 6, by + 4);

    // Hover tooltip
    if (zoningHover >= 0) {
        const b = LAYOUT[zoningHover];
        const label = `${b.zone.name} — ${fmt.n(b.zone.area)} m² (${b.zone.pct}%)`;
        ctx.font = '600 12px system-ui, sans-serif';
        const tw = ctx.measureText(label).width + 18;
        const tx = Math.min(Math.max(px(b.x + b.w / 2) - tw / 2, 4), W - tw - 4);
        const ty = Math.max(py(b.y + b.h) - 30, 4);
        ctx.fillStyle = cssVar('--bg-raised');
        ctx.strokeStyle = cssVar('--line');
        ctx.beginPath();
        if (ctx.roundRect) ctx.roundRect(tx, ty, tw, 24, 6); else ctx.rect(tx, ty, tw, 24);
        ctx.fill(); ctx.stroke();
        ctx.fillStyle = cssVar('--text');
        ctx.fillText(label, tx + 9, ty + 16);
    }

    canvas._geom = { px, py, scale };
}

