function makeSortable(tableId) {
    const table = document.getElementById(tableId);
    if (!table) return;
    const heads = $$('th.sortable', table);
    heads.forEach((th, col) => {
        th.setAttribute('role', 'button');
        th.setAttribute('tabindex', '0');
        const sort = () => {
            const body = $('tbody', table);
            const dir = th.getAttribute('aria-sort') === 'ascending' ? -1 : 1;
            heads.forEach(h => h.removeAttribute('aria-sort'));
            th.setAttribute('aria-sort', dir === 1 ? 'ascending' : 'descending');
            const index = Array.from(th.parentNode.children).indexOf(th);
            const rows = $$('tr', body);
            rows.sort((a, b) => {
                const av = a.children[index].dataset.sort ?? a.children[index].innerText;
                const bv = b.children[index].dataset.sort ?? b.children[index].innerText;
                const an = parseFloat(String(av).replace(/[^0-9.-]/g, ''));
                const bn = parseFloat(String(bv).replace(/[^0-9.-]/g, ''));
                if (!isNaN(an) && !isNaN(bn)) return (an - bn) * dir;
                return String(av).localeCompare(String(bv)) * dir;
            });
            rows.forEach(r => body.appendChild(r));
        };
        th.addEventListener('click', sort);
        th.addEventListener('keydown', e => {
            if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); sort(); }
        });
    });
}

