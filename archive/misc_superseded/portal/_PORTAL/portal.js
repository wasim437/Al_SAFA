function applyTheme(theme) {
    document.documentElement.setAttribute('data-theme', theme);
    try { localStorage.setItem(THEME_KEY, theme); } catch (e) { /* private mode */ }
    $('#themeToggle').textContent = theme === 'dark' ? '◐' : '◑';
    rebuildAllCharts();
    redrawCanvases();
}

