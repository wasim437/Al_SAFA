const fmt = {
    n:   (v, d = 0) => Number(v).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }),
    aed: (v) => 'AED ' + fmt.n(v),
    m:   (v) => (v / 1e6).toFixed(v >= 1e7 ? 1 : 2) + 'M',
    pct: (v, d = 1) => Number(v).toFixed(d) + '%',
    /** 12.5 -> "12:30" */
    clock: (h) => {
        const hh = Math.floor(h), mm = Math.round((h - hh) * 60);
        return String(mm === 60 ? hh + 1 : hh).padStart(2, '0') + ':' +
               String(mm === 60 ? 0 : mm).padStart(2, '0');
    },
};

/** Escape text destined for innerHTML. */
function esc(s) {
    return String(s).replace(/[&<>"']/g, c =>
        ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

/** Read a themed colour from CSS custom properties. */
function cssVar(name) {
    return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

/** rgba() from a hex token plus alpha. */
function alpha(hex, a) {
    const h = hex.replace('#', '');
    const full = h.length === 3 ? h.split('').map(c => c + c).join('') : h;
    const n = parseInt(full, 16);
    return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${a})`;
}

