const charts = {};        // id -> Chart instance
const chartFactories = {}; // id -> () => config

function chart(id, factory) {
    chartFactories[id] = factory;
}

function buildChart(id) {
    const canvas = document.getElementById(id);
    if (!canvas || !chartFactories[id]) return;
    if (charts[id]) charts[id].destroy();
    charts[id] = new Chart(canvas, chartFactories[id]());
}

function rebuildAllCharts() {
    Object.keys(charts).forEach(buildChart);
}

