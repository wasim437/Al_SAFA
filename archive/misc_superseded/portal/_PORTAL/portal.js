/**
 * Render a KPI tile. When `provKey` names a tracked metric the tile becomes a
 * button that opens the provenance drawer — that is the mechanism that makes
 * every headline figure auditable in one click.
 */
function kpi({ value, unit, label, sub, tone = 'blue', provKey = null }) {
    const tag = provKey ? 'button' : 'div';
    const attrs = provKey ? ` data-prov="${esc(provKey)}"` : '';
    return `<${tag} class="kpi ${tone}"${attrs}>
        <div class="kpi-val">${esc(value)}${unit ? `<span class="unit">${esc(unit)}</span>` : ''}</div>
        <div class="kpi-label">${esc(label)}</div>
        ${sub ? `<div class="kpi-sub">${esc(sub)}</div>` : ''}
    </${tag}>`;
}

