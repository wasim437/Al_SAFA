/* ==========================================================================
   11. Solar engine — NOAA solar position algorithm
   --------------------------------------------------------------------------
   Implemented in full rather than interpolated from a table, so any date and
   time can be inspected. Validated on the Solar page against the project's own
   pvlib NREL SPA output for the three key dates.
   ========================================================================== */
const SITE = D.solar.site;              // lat / lon / elevation
const TZ = 4;                           // Asia/Dubai, no DST

const rad = d => d * Math.PI / 180;
const deg = r => r * 180 / Math.PI;

function julianDay(year, month, day, hourLocal) {
    let y = year, m = month;
    if (m <= 2) { y -= 1; m += 12; }
    const A = Math.floor(y / 100);
    const B = 2 - A + Math.floor(A / 4);
    const jd0 = Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1))
              + day + B - 1524.5;
    return jd0 + (hourLocal - TZ) / 24;
}

/**
 * @returns {{elevation, azimuth, declination, eqTime, sunrise, sunset,
 *            solarNoon, dayLength}} angles in degrees, times in local hours.
 */
function solarPosition(year, month, day, hourLocal) {
    const jd = julianDay(year, month, day, hourLocal);
    const jc = (jd - 2451545.0) / 36525.0;

    const gmls = (280.46646 + jc * (36000.76983 + jc * 0.0003032)) % 360;
    const gmas = 357.52911 + jc * (35999.05029 - 0.0001537 * jc);
    const ecc  = 0.016708634 - jc * (0.000042037 + 0.0000001267 * jc);

    const ctr = Math.sin(rad(gmas)) * (1.914602 - jc * (0.004817 + 0.000014 * jc))
              + Math.sin(rad(2 * gmas)) * (0.019993 - 0.000101 * jc)
              + Math.sin(rad(3 * gmas)) * 0.000289;

    const trueLong = gmls + ctr;
    const appLong  = trueLong - 0.00569 - 0.00478 * Math.sin(rad(125.04 - 1934.136 * jc));

    const meanObliq = 23 + (26 + ((21.448 - jc * (46.815 + jc * (0.00059 - jc * 0.001813)))) / 60) / 60;
    const obliq = meanObliq + 0.00256 * Math.cos(rad(125.04 - 1934.136 * jc));

    const declination = deg(Math.asin(Math.sin(rad(obliq)) * Math.sin(rad(appLong))));

    const varY = Math.tan(rad(obliq / 2)) ** 2;
    const eqTime = 4 * deg(
        varY * Math.sin(2 * rad(gmls))
        - 2 * ecc * Math.sin(rad(gmas))
        + 4 * ecc * varY * Math.sin(rad(gmas)) * Math.cos(2 * rad(gmls))
        - 0.5 * varY * varY * Math.sin(4 * rad(gmls))
        - 1.25 * ecc * ecc * Math.sin(2 * rad(gmas)));

    // Hour angle of sunrise, using the standard 90.833° zenith (refraction + disc).
    const cosHa = Math.cos(rad(90.833)) / (Math.cos(rad(SITE.lat)) * Math.cos(rad(declination)))
                - Math.tan(rad(SITE.lat)) * Math.tan(rad(declination));
    const haSunrise = Math.abs(cosHa) <= 1 ? deg(Math.acos(cosHa)) : (cosHa > 1 ? 0 : 180);

    const solarNoonMin = 720 - 4 * SITE.lon - eqTime + TZ * 60;
    const sunrise = (solarNoonMin - haSunrise * 4) / 60;
    const sunset  = (solarNoonMin + haSunrise * 4) / 60;

    // True solar time -> hour angle -> zenith.
    let tst = (hourLocal * 60 + eqTime + 4 * SITE.lon - 60 * TZ) % 1440;
    if (tst < 0) tst += 1440;
    const ha = tst / 4 < 0 ? tst / 4 + 180 : tst / 4 - 180;

    const cosZen = Math.sin(rad(SITE.lat)) * Math.sin(rad(declination))
                 + Math.cos(rad(SITE.lat)) * Math.cos(rad(declination)) * Math.cos(rad(ha));
    const zenith = deg(Math.acos(Math.min(1, Math.max(-1, cosZen))));
    const elevation = 90 - zenith;

    let azimuth;
    const denom = Math.cos(rad(SITE.lat)) * Math.sin(rad(zenith));
    if (Math.abs(denom) < 1e-9) {
        azimuth = 180;
    } else {
        const cosAz = (Math.sin(rad(SITE.lat)) * Math.cos(rad(zenith)) - Math.sin(rad(declination))) / denom;
        const az = deg(Math.acos(Math.min(1, Math.max(-1, cosAz))));
        azimuth = ha > 0 ? (az + 180) % 360 : (540 - az) % 360;
    }

    return {
        elevation, azimuth, declination, eqTime,
        sunrise, sunset, solarNoon: solarNoonMin / 60,
        dayLength: haSunrise * 8 / 60,
    };
}

/** Peak elevation for a date, found by scanning the day at 1-minute steps. */
function peakElevation(year, month, day) {
    const noon = solarPosition(year, month, day, 12).solarNoon;
    let best = -90;
    for (let h = noon - 0.5; h <= noon + 0.5; h += 1 / 60) {
        best = Math.max(best, solarPosition(year, month, day, h).elevation);
    }
    return best;
}

